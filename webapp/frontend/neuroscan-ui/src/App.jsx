
import { useState } from "react";
import "./App.css";


const API_URL = `${
  import.meta.env.VITE_API_BASE_URL || "http://127.0.0.1:8000"
}/predict`;


const CLASS_NAMES = [
  "NonDemented",
  "VeryMildDemented",
  "MildDemented",
  "ModerateDemented",
];

function App() {
  const [file, setFile] = useState(null);
  const [preview, setPreview] = useState("");
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  function handleFileChange(event) {
    const selectedFile = event.target.files?.[0];

    if (!selectedFile) return;

    if (!["image/jpeg", "image/png"].includes(selectedFile.type)) {
      setError("Please select a JPG or PNG MRI image.");
      return;
    }

    if (selectedFile.size > 10 * 1024 * 1024) {
      setError("Image must be smaller than 10 MB.");
      return;
    }

    setFile(selectedFile);
    setPreview(URL.createObjectURL(selectedFile));
    setResult(null);
    setError("");
  }

  async function analyzeMRI() {
    if (!file) {
      setError("Please upload an MRI image first.");
      return;
    }

    setLoading(true);
    setError("");
    setResult(null);

    const formData = new FormData();
    formData.append("file", file);

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        body: formData,
      });

      if (!response.ok) {
        const details = await response.json().catch(() => ({}));
        throw new Error(
          details.detail || "Unable to analyze the MRI image."
        );
      }

      const data = await response.json();
      setResult(data);
    } catch (err) {
      setError(
        err.message === "Failed to fetch"
          ? "Cannot connect to FastAPI. Check that the backend is running."
          : err.message
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="app">
      <header className="navbar">
        <div className="brand">
          <span className="brand-icon">✦</span>
          NeuroScan <span>AI</span>
        </div>
        <div className="nav-label">MRI Classification Research</div>
      </header>

      <main className="main-content">
        <div className="hero">
          <div className="eyebrow">AI-POWERED MRI ANALYSIS</div>
          <h1>Brain MRI Classification</h1>
          <p>
            Upload a brain MRI image and explore predictions
            generated by a trained convolutional neural network.
          </p>
        </div>

        <div className="workspace">
          <section className="panel upload-panel">
            <h2>Upload MRI Image</h2>
            <p className="panel-description">
              Select a 2D brain MRI image in JPG or PNG format.
            </p>

            <label className="upload-zone">
              {preview ? (
                <img
                  src={preview}
                  alt="Selected brain MRI"
                  className="mri-preview"
                />
              ) : (
                <div className="upload-placeholder">
                  <div className="upload-symbol">↑</div>
                  <strong>Choose an MRI image</strong>
                  <span>JPG or PNG · Maximum 10 MB</span>
                </div>
              )}

              <input
                type="file"
                accept=".jpg,.jpeg,.png,image/jpeg,image/png"
                onChange={handleFileChange}
                hidden
              />
            </label>

            {file && (
              <p className="filename">{file.name}</p>
            )}

            <button
              className="analyze-button"
              onClick={analyzeMRI}
              disabled={loading || !file}
            >
              {loading ? "Analyzing MRI..." : "Analyze MRI"}
            </button>

            {error && (
              <p className="error-message" role="alert">
                {error}
              </p>
            )}
          </section>

          <section className="panel results-panel">
            <h2>Classification Results</h2>
            <p className="panel-description">
              Predictions from your trained CNN V2 model.
            </p>

            {!result ? (
              <div className="empty-results">
                <div className="empty-symbol">◎</div>
                <h3>No analysis yet</h3>
                <p>
                  Upload an MRI and click Analyze MRI to
                  display the model's prediction.
                </p>
              </div>
            ) : (
              <div className="prediction-results">
                <div className="prediction-card">
                  <span>Predicted category</span>
                  <h3>{result.predicted_class}</h3>
                  <div className="confidence">
                    {result.confidence.toFixed(2)}%
                  </div>
                  <small>Highest model output score</small>
                </div>

                <h3 className="scores-heading">
                  Class probabilities
                </h3>

                {CLASS_NAMES.map((name) => {
                  const probability =
                    result.probabilities[name] ?? 0;

                  return (
                    <div className="score-row" key={name}>
                      <div className="score-label">
                        <span>{name}</span>
                        <span>
                          {probability.toFixed(2)}%
                        </span>
                      </div>

                      <div className="progress-track">
                        <div
                          className={
                            name === result.predicted_class
                              ? "progress-fill selected"
                              : "progress-fill"
                          }
                          style={{
                            width: `${probability}%`,
                          }}
                        />
                      </div>
                    </div>
                  );
                })}
              </div>
            )}
          </section>
        </div>

        <div className="disclaimer">
          <strong>Research use only.</strong> This application
          is an educational demonstration, not a medical
          diagnostic tool. The model has not been clinically
          validated and has known limitations in recognizing
          ModerateDemented images.
        </div>
      </main>

      <footer className="footer">
        NeuroScan AI · Biomedical Engineering Research Project
      </footer>
    </div>
  );
}

export default App;
